#!/usr/bin/env python3
"""Generate the four wheel-corner sketches from the motor_node template.

    python3 firmware/make_corner_sketches.py

Reads  firmware/motor_node/motor_node.ino  (the template; edit firmware there)
Writes firmware/motor_node_<CORNER>/motor_node_<CORNER>.ino  for LF, RF, LR, RR,
       plus a name.c in each that sets the USB product name to "Motor_<CORNER>",
       so a flashed board shows up as /dev/serial/by-id/usb-Teensyduino_Motor_LF_<serial>-if00.

The sketches are identical except for the PER-BOARD CONFIGURATION block, which
comes from CORNERS below. Change per-corner values here, then rerun.
"""

import os
import re
import sys

FIRMWARE_DIR = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(FIRMWARE_DIR, "motor_node", "motor_node.ino")

# corner: (MAC last byte, ENCODER_SIGN, note on the sign)
# MAC bytes must be unique. LF keeps old motor 1's byte (1), so it keeps its DHCP lease.
CORNERS = {
    "LF": (1, -1, "verified 2026-11-02 (this board was motor 1)"),
    "RF": (2, -1, "NOT VERIFIED - check positive effort reads positive rpm, flip if not"),
    "LR": (3, -1, "NOT VERIFIED - check positive effort reads positive rpm, flip if not"),
    "RR": (4, -1, "NOT VERIFIED - check positive effort reads positive rpm, flip if not"),
}

# Factory USB serial number of the Teensy that belongs to each corner: the number in
# /dev/serial/by-id/usb-Teensyduino_Motor_<corner>_<serial>-if00. It's fixed in the
# board's hardware, so reflashing, unplugging and replugging don't change it.
# firmware/find_boards.py uses it to find each corner's board before flashing.
# It identifies the Teensy, not the motor: if a board moves to another motor or gets
# replaced, update this table.
# Recorded 2026-11-09 from the corner firmware each board was running.
BOARD_SERIALS = {
    "LF": "20416110",
    "RF": "20416240",
    "LR": "20416150",
    "RR": "20416000",
}

BLOCK_RE = re.compile(r"^// @@BOARD_CONFIG_BEGIN@@\n.*?^// @@BOARD_CONFIG_END@@\n",
                      re.MULTILINE | re.DOTALL)

HEADER = """\
// ****************************************************************************
// GENERATED FILE - DO NOT EDIT. Edit firmware/motor_node/motor_node.ino, then
// run `python3 firmware/make_corner_sketches.py` to regenerate all 4 corners.
// ****************************************************************************
"""

BLOCK = """\
// Values come from CORNERS in firmware/make_corner_sketches.py.
#define MOTOR_NAME "{name}"            // wheel corner: sets the MQTT topics and client ID
const uint8_t MAC_LAST_BYTE = {mac};      // unique per board
const long ENCODER_SIGN = {sign};         // {note}
"""

NAME_C = """\
// GENERATED by firmware/make_corner_sketches.py - do not edit.
// Sets the USB product name, so this board shows up in Linux as
// /dev/serial/by-id/usb-Teensyduino_{product}_<serial number>-if00
#include "usb_names.h"

#define PRODUCT_NAME      {{{chars}}}
#define PRODUCT_NAME_LEN  {length}

struct usb_string_descriptor_struct usb_string_product_name = {{
  2 + PRODUCT_NAME_LEN * 2,
  3,
  PRODUCT_NAME
}};
"""


def write_if_changed(path: str, text: str) -> bool:
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def main():
    with open(TEMPLATE, encoding="utf-8") as f:
        template = f.read()
    if len(BLOCK_RE.findall(template)) != 1:
        sys.exit(f"✗ {TEMPLATE} must contain exactly one @@BOARD_CONFIG_BEGIN@@/END@@ block")

    macs = [mac for mac, _, _ in CORNERS.values()]
    if len(set(macs)) != len(macs):
        sys.exit("✗ MAC bytes in CORNERS must be unique")
    if set(BOARD_SERIALS) != set(CORNERS):
        sys.exit("✗ BOARD_SERIALS must list exactly the corners in CORNERS")
    if len(set(BOARD_SERIALS.values())) != len(BOARD_SERIALS):
        sys.exit("✗ serial numbers in BOARD_SERIALS must be unique")

    for name, (mac, sign, note) in CORNERS.items():
        if sign not in (1, -1):
            sys.exit(f"✗ {name}: ENCODER_SIGN must be 1 or -1")
        sketch = f"motor_node_{name}"
        out_dir = os.path.join(FIRMWARE_DIR, sketch)
        os.makedirs(out_dir, exist_ok=True)

        block = BLOCK.format(name=name, mac=mac, sign=sign, note=note)
        ino = HEADER + BLOCK_RE.sub(lambda _: block, template)
        product = f"Motor_{name}"
        name_c = NAME_C.format(product=product, chars=",".join(f"'{c}'" for c in product),
                               length=len(product))

        changed = [fn for fn, text in ((f"{sketch}.ino", ino), ("name.c", name_c))
                   if write_if_changed(os.path.join(out_dir, fn), text)]
        status = ("updated " + ", ".join(changed)) if changed else "unchanged"
        print(f"{name}: firmware/{sketch}/  ({status})  ENCODER_SIGN={sign:+d}  {note}")


if __name__ == "__main__":
    main()
